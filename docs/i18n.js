// done 里除了词典译文，还会记下带变量的译文（时间、数字），超过上限就重置回只含词典译文
function resetDone() { I18N.done.clear(); for (const [, ja, en] of ENTRIES) { I18N.done.add(ja); I18N.done.add(en); } }
